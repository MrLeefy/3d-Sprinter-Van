// Generates docs/ACCEPTANCE-REPORT.md from the live model (npm run report).
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runAcceptance } from '../src/sim/acceptance.js';
import { weightReport } from '../src/sim/weight.js';
import { costReport } from '../src/sim/cost.js';
import { spaceReport } from '../src/sim/space.js';
import { runScenario, endurance, CATEGORIES } from '../src/sim/model.js';
import { designHeatLoss, designCoolingLoad, envelopeUA, nightVentM3h, steadyCO2 } from '../src/sim/thermal.js';
import { SCENARIOS } from '../src/data/scenarios.js';
import { COMPONENTS, CERT } from '../src/data/components.js';
import { HEATER, acCapacityW } from '../src/data/climate.js';
import { BANK } from '../src/data/electrical.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const r = (v, d = 0) => Number(v).toFixed(d);
const acc = runAcceptance();
const w = weightReport();
const c = costReport();
const s = spaceReport();
const hl = designHeatLoss({ Tout: -20, Tin: 20, covers: 1, ventM3h: nightVentM3h() });
const cl = designCoolingLoad({ Tout: 38, Tin: 26, ghi: 920, covers: 1 });
const ua = envelopeUA({ covers: 1 });
const LIMIT = { battery: 'battery 20 %', fresh: 'fresh water empty', grey: 'grey tank full', urine: 'urine bottle full', solids: 'solids bin full', fuel: 'fuel at ¼' };

let md = `# Acceptance report

Generated by \`npm run report\` from the same model the interactive viewer uses.

**Result: ${acc.summary.pass} pass · ${acc.summary.warn} warn · ${acc.summary.fail} fail**

## Checks
`;
for (const cat of [...new Set(acc.checks.map((x) => x.cat))]) {
  md += `\n### ${cat}\n\n| | Check | Value | Limit |\n|---|---|---|---|\n`;
  for (const x of acc.checks.filter((y) => y.cat === cat)) {
    md += `| ${x.status === 'pass' ? '✅' : x.status === 'warn' ? '⚠️' : '❌'} | ${x.name}${x.detail ? `<br><sub>${x.detail}</sub>` : ''} | ${x.value} | ${x.limit} |\n`;
  }
}
md += `
## Weight & axle loads (2 occupants, full fresh water, 104 kg gear)

| Item | Value |
|---|---|
| Dry conversion mass | ${r(w.build)} kg |
| Gross vehicle weight | ${r(w.gvw)} kg of ${w.gvwr} kg GVWR |
| Front axle | ${r(w.front)} kg of ${w.gawrFront} kg GAWR |
| Rear axle | ${r(w.rear)} kg of ${w.gawrRear} kg GAWR |
| Payload remaining | ${r(w.payloadLeft)} kg |
| Centre of gravity | x = ${r(w.cg[0], 2)} m ahead of rear axle, y = ${r(w.cg[1], 2)} m, lateral ${r(w.lateralOffsetMm)} mm |

## Heating & cooling demand

| Case | Value |
|---|---|
| Envelope UA (window covers on) | ${r(ua.total, 1)} W/K |
| Heat loss at −20 °C outside / 20 °C inside | ${r(hl.total)} W (heater ${HEATER.dieselStagesW[2]} W → ${r(HEATER.dieselStagesW[2] / hl.total, 1)}× margin) |
| Cooling load at 38 °C, full sun, 26 °C inside | ${r(cl.total)} W (AC ${r(acCapacityW(38))} W → ${r((100 * acCapacityW(38)) / cl.total)} %) |
| Night CO₂, 2 sleepers, sealed van | ${r(steadyCO2(2, nightVentM3h() + 5.4))} ppm |

## Daily budgets & endurance by scenario

| Scenario | Use kWh/day | Harvest kWh/day | Water L/day | Diesel L/day | Lowest battery | First limit (no resupply) |
|---|---|---|---|---|---|---|
`;
for (const sc of SCENARIOS) {
  const run = runScenario(sc, {}, { days: sc.days, dt: 60 });
  const e = endurance(sc, {}, 10);
  md += `| ${sc.name} | ${r(run.perDay.loadWh / 1000, 1)} | ${r((run.perDay.solarWh + run.perDay.altWh) / 1000, 1)} | ${r(run.perDay.waterL)} | ${r(run.perDay.dieselL, 2)} | ${r(run.minSoc * 100)} % | ${e.first ? `${LIMIT[e.first.id]} after ${r(e.first.days, 1)} d` : 'none in 10 d'} |\n`;
}
const run = runScenario(SCENARIOS[5]);
md += `\nEnergy by use, 5-day off-grid scenario (Wh/day): ${Object.entries(run.perDay.byCat).map(([k, v]) => `${CATEGORIES[k]} ${r(v)}`).join(' · ')}\n`;
md += `
## Space

| Item | Value |
|---|---|
| Finished cargo floor | ${r(s.grossFloor, 2)} m² |
| Built-in footprint | ${r(s.builtFloor, 2)} m² |
| Clear standing floor (1.89 m headroom) | ${r(s.standing, 2)} m² |
| Enclosed storage | ${r(s.storageL)} L |
| Bed | 1.33 × ${s.bed.retracted} m (${s.bed.deployed} m with pod) |
| House battery | ${(BANK.capacityWh / 1000).toFixed(2)} kWh |

## Cost estimate (USD, 2026)

| System | Parts |
|---|---|
${c.rows.map((x) => `| ${x.name} | $${x.cost.toLocaleString('en-US')} |`).join('\n')}
| Contingency 10 % | $${c.contingency.toLocaleString('en-US')} |
| **DIY build** | **$${c.diy.toLocaleString('en-US')}** |
| **Professional build** (${c.labor.proHours} h) | **$${c.pro.toLocaleString('en-US')}** |
| Turn-key incl. base van | $${c.totalPro.toLocaleString('en-US')} |

## Items requiring licensed sign-off

${COMPONENTS.filter((x) => x.cert).map((x) => `- **${x.name}** — ${CERT[x.cert]}`).join('\n')}
`;
writeFileSync(join(root, 'docs', 'ACCEPTANCE-REPORT.md'), md);
console.log(`docs/ACCEPTANCE-REPORT.md — ${acc.summary.pass} pass, ${acc.summary.warn} warn, ${acc.summary.fail} fail`);
